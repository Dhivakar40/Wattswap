VECTORS = Path(__file__).resolve().parents[3] / "packages" / "shared" / "vectors" / "eip712.json"


def payload(ghi: list[object] | None = None, temp: list[object] | None = None) -> dict[str, object]:
    return {
        "hourly": {
            "shortwave_radiation": ghi if ghi is not None else [float(i) for i in range(24)],
            "temperature_2m": temp if temp is not None else [20.0] * 24,
        }
    }


# ----------------------------------------------------------------------------- signing
def test_signature_matches_solidity_vector() -> None:
    """Python signs the same digest as the contracts (vector generated by Foundry)."""
    vectors = json.loads(VECTORS.read_text(encoding="utf-8"))
    v = next(x for x in vectors["vectors"] if x["name"] == "meter_reading")
    msg = v["typedData"]["message"]
    domain = v["typedData"]["domain"]
    signed = sign_with_id(
        vectors["testKeys"]["device"],
        domain["chainId"],
        domain["verifyingContract"],
        msg["meterId"],
        msg["readingId"],
        msg["amountWh"],
        msg["intervalStart"],
        msg["intervalSeconds"],
    )
    assert signed.signature == v["signature"]
    data = typed_data(
        domain["chainId"],
        domain["verifyingContract"],
        msg["meterId"],
        msg["readingId"],
        msg["amountWh"],
        msg["intervalStart"],
        msg["intervalSeconds"],
    )
    digest = encode_typed_data(full_message=data)
    assert Account.recover_message(digest, signature=signed.signature) == v["signer"]


def test_reading_id_is_deterministic_per_interval() -> None:
    m = "0x" + "11" * 32
    assert derive_reading_id(m, 1_800_000_000, 900) == derive_reading_id(m, 1_800_000_000, 900)
    assert derive_reading_id(m, 1_800_000_000, 900) != derive_reading_id(m, 1_800_000_900, 900)
    assert derive_reading_id(m, 1_800_000_000, 900) != derive_reading_id(m, 1_800_000_000, 1800)



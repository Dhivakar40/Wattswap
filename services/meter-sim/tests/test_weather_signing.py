def test_parse_accepts_valid_and_rejects_garbage() -> None:
    assert parse_open_meteo(payload()) is not None
    assert parse_open_meteo({}) is None
    assert parse_open_meteo(payload(ghi=[1.0] * 23)) is None
    assert parse_open_meteo(payload(ghi=[None] * 24)) is None
    assert parse_open_meteo(payload(ghi=[float("nan")] * 24)) is None
    assert parse_open_meteo(payload(ghi=[99999.0] * 24)) is None  # untrusted wire data
    assert parse_open_meteo(payload(temp=[500.0] * 24)) is None
    assert parse_open_meteo(payload(ghi=[True] * 24)) is None
    assert parse_open_meteo("nope") is None


def test_interpolation_between_hours() -> None:
    pts = [WeatherPoint(float(h * 10), 20.0) for h in range(24)]
    mid = interpolate(pts, datetime(2026, 1, 1, 6, 30, tzinfo=UTC))
    assert mid.ghi_wm2 == pytest.approx(65.0)
    assert interpolate(pts, datetime(2026, 1, 1, 23, 45, tzinfo=UTC)).ghi_wm2 == 230.0


@respx.mock
async def test_open_meteo_success_is_cached_and_uses_archive_for_old_days() -> None:
    route = respx.get(ARCHIVE_URL).mock(return_value=httpx.Response(200, json=payload()))
    prov = OpenMeteoProvider(backoff_s=0, today=date(2026, 10, 18))
    day = date(2026, 10, 1)
    first = await prov.day(13.08, 80.27, day)
    second = await prov.day(13.08, 80.27, day)
    assert first is not None and first == second
    assert route.call_count == 1  # cached
    assert route.calls.last.request.url.params["start_date"] == "2026-10-01"
    await prov.aclose()


@respx.mock
async def test_open_meteo_recent_days_use_forecast_endpoint() -> None:
    route = respx.get(FORECAST_URL).mock(return_value=httpx.Response(200, json=payload()))
    prov = OpenMeteoProvider(backoff_s=0, today=date(2026, 10, 18))
    assert await prov.day(13.08, 80.27, date(2026, 10, 17)) is not None
    assert route.called
    await prov.aclose()


@respx.mock
async def test_open_meteo_retries_then_falls_back() -> None:
    route = respx.get(FORECAST_URL).mock(return_value=httpx.Response(503))
    prov = OpenMeteoProvider(retries=2, backoff_s=0, today=date(2026, 10, 18))
    assert await prov.day(1.0, 2.0, date(2026, 10, 18)) is None
    assert route.call_count == 3
    await prov.aclose()


@respx.mock
async def test_open_meteo_recovers_after_transient_failure() -> None:
    respx.get(FORECAST_URL).mock(
        side_effect=[httpx.Response(429), httpx.Response(200, json=payload())]
    )
    prov = OpenMeteoProvider(retries=2, backoff_s=0, today=date(2026, 10, 18))
    assert await prov.day(1.0, 2.0, date(2026, 10, 18)) is not None
    await prov.aclose()


@respx.mock
async def test_open_meteo_malformed_body_falls_back() -> None:
    respx.get(FORECAST_URL).mock(return_value=httpx.Response(200, json={"hourly": {}}))
    prov = OpenMeteoProvider(retries=0, backoff_s=0, today=date(2026, 10, 18))
    assert await prov.day(1.0, 2.0, date(2026, 10, 18)) is None

/**
 * Cross-language SIWE gate, frontend half. The cases below are built with the app's own EIP-4361
 * builder, signed with Anvil dev keys (deterministic RFC 6979 signatures) and compared with the
 * committed fixture packages/shared/vectors/siwe-frontend.json. The backend half
 * (services/api/tests/unit/test_siwe_frontend_fixture.py) parses and verifies the same file with the
 * Python `siwe` library that production login uses. Regenerate with UPDATE_FIXTURES=1.
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { privateKeyToAccount } from "viem/accounts";
import { describe, expect, it } from "vitest";
import { buildSiweMessage, loginFields, SiweError, type SiweFields } from "@/lib/auth/siwe";
import { ANVIL_CHAIN_ID, anvilKey, assertAnvil } from "./helpers/dev-keys";

const FIXTURE = resolve(__dirname, "../../../packages/shared/vectors/siwe-frontend.json");
const T0 = new Date("2026-10-19T12:00:00.000Z");
const min = (m: number): Date => new Date(T0.getTime() + m * 60_000);
const addr = (i: number): string => privateKeyToAccount(anvilKey(i, ANVIL_CHAIN_ID)).address;
const STATEMENT = "Sign in to WattSwap (testnet demo).";

interface Case {
  name: string;
  key: number;
  fields: SiweFields;
}


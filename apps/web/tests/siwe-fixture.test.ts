async function generate(): Promise<unknown> {
  const cases = [];
  for (const c of CASES) {
    const account = privateKeyToAccount(anvilKey(c.key, ANVIL_CHAIN_ID));
    const message = buildSiweMessage(c.fields);
    const signature = await account.signMessage({ message });
    const f = c.fields;
    cases.push({
      name: c.name,
      signer: account.address,
      message,
      signature,
      expect: {
        scheme: f.scheme ?? null,
        domain: f.domain,
        address: account.address,
        statement: f.statement ?? null,
        uri: f.uri,
        chain_id: f.chainId,
        nonce: f.nonce,
        issued_at: f.issuedAt.toISOString(),
        expiration_time: f.expirationTime?.toISOString() ?? null,
        not_before: f.notBefore?.toISOString() ?? null,
        request_id: f.requestId ?? null,
        resources: f.resources ?? [],
      },
    });
  }
  return {
    $comment:
      "Generated by apps/web/tests/siwe-fixture.test.ts (UPDATE_FIXTURES=1). Verified by services/api/tests/unit/test_siwe_frontend_fixture.py with the Python siwe library. Anvil dev keys only.",
    cases,
  };
}

describe("SIWE builder cross-language fixture", () => {
  it("matches the committed fixture byte for byte (UPDATE_FIXTURES=1 regenerates)", async () => {
    const fresh = JSON.stringify(await generate(), null, 2) + "\n";
    if (process.env.UPDATE_FIXTURES === "1") writeFileSync(FIXTURE, fresh, "utf-8");
    expect(existsSync(FIXTURE)).toBe(true);
    expect(readFileSync(FIXTURE, "utf-8")).toBe(fresh);
  });
});

describe("buildSiweMessage", () => {
  const base: SiweFields = {
    domain: "localhost:3000",
    address: addr(0),
    statement: STATEMENT,
    uri: "http://localhost:3000",
    chainId: 31337,
    nonce: "abcdefgh1234",
    issuedAt: T0,
    expirationTime: min(5),
  };

  it("produces the documented template (docs/api.md) exactly", () => {
    expect(buildSiweMessage(base)).toBe(
      [
        "localhost:3000 wants you to sign in with your Ethereum account:",
        "0xf39Fd6e51aad88F6F4ce6aB8827279cffFb92266",
        "",
        STATEMENT,
        "",
        "URI: http://localhost:3000",
        "Version: 1",
        "Chain ID: 31337",
        "Nonce: abcdefgh1234",
        "Issued At: 2026-10-19T12:00:00.000Z",
        "Expiration Time: 2026-10-19T12:05:00.000Z",
      ].join("\n"),
    );
  });

  it("rejects injection through line breaks and malformed inputs", () => {
    expect(() => buildSiweMessage({ ...base, statement: "a\nURI: https://evil" })).toThrow(
      SiweError,
    );
    expect(() => buildSiweMessage({ ...base, domain: "a\nb" })).toThrow(SiweError);
    expect(() => buildSiweMessage({ ...base, nonce: "short" })).toThrow(SiweError);
    expect(() => buildSiweMessage({ ...base, nonce: "has space 12345" })).toThrow(SiweError);
    expect(() => buildSiweMessage({ ...base, chainId: 0 })).toThrow(SiweError);
    expect(() => buildSiweMessage({ ...base, address: "0x1234" })).toThrow();
  });

  it("derives domain and uri from the page origin (wallets check this)", () => {
    const f = loginFields({
      address: base.address,
      chainId: 31337,
      nonce: "abcdefgh1234",
      origin: "https://app.example.com:8443",
      now: T0,
    });
    expect(f.domain).toBe("app.example.com:8443");
    expect(f.uri).toBe("https://app.example.com:8443");
    expect(f.expirationTime?.getTime()).toBe(T0.getTime() + 5 * 60_000);
  });
});

describe("dev keys", () => {
  it("refuse to be used off Anvil", () => {
    expect(() => assertAnvil(1)).toThrow(/refusing/);
    expect(() => anvilKey(0, 11155111)).toThrow(/refusing/);
    expect(() => anvilKey(99, 31337)).toThrow(RangeError);
    expect(anvilKey(0, 31337)).toMatch(/^0x[0-9a-f]{64}$/);
  });
});

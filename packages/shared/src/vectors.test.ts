import { hashTypedData, recoverTypedDataAddress, type Hex, type TypedDataDomain } from "viem";
import { privateKeyToAddress } from "viem/accounts";
import { describe, expect, it } from "vitest";
import vectors from "../vectors/eip712.json";

/** Plain JSON numbers -> bigint for uint types, so viem can hash them. */
function toBigInts(value: unknown): unknown {
  if (typeof value === "number") return BigInt(value);
  if (Array.isArray(value)) return value.map(toBigInts);
  if (value !== null && typeof value === "object") {
    return Object.fromEntries(Object.entries(value).map(([k, v]) => [k, toBigInts(v)]));
  }
  return value;
}

describe("EIP-712 test vectors (generated by Foundry from the real contracts)", () => {
  it("has the expected vectors", () => {
    expect(vectors.vectors.map((v) => v.name)).toEqual([
      "order_buy",
      "order_sell",
      "price_quote",
      "meter_reading",
      "price_quote_min_price",
      "price_quote_night",
      "price_quote_max_safe_price",
      "price_quote_second_market",
    ]);
  });

  for (const v of vectors.vectors) {
    it(`${v.name}: viem digest, domain and signer match the contract-produced values`, async () => {
      const typedData = toBigInts(v.typedData) as {
        types: Record<string, { name: string; type: string }[]>;
        primaryType: string;
        domain: TypedDataDomain;
        message: Record<string, unknown>;
      };
      const { EIP712Domain: _domainType, ...types } = typedData.types;
      void _domainType;

      const digest = hashTypedData({
        domain: typedData.domain,
        types,
        primaryType: typedData.primaryType,
        message: typedData.message,
      });
      expect(digest).toBe(v.digest);

      const recovered = await recoverTypedDataAddress({
        domain: typedData.domain,
        types,
        primaryType: typedData.primaryType,
        message: typedData.message,
        signature: v.signature as Hex,
      });
      expect(recovered).toBe(v.signer);
    });
  }

  it("declared signers derive from the published test keys", () => {
    const keys = vectors.testKeys;
    const keyFor = (name: string): string => {
      if (name.startsWith("price_quote")) return keys.pricer;
      if (name === "order_buy") return keys.buyer;
      if (name === "order_sell") return keys.seller;
      return keys.device;
    };
    for (const v of vectors.vectors) {
      expect(privateKeyToAddress(keyFor(v.name) as Hex)).toBe(v.signer);
    }
  });
});

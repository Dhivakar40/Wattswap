#!/usr/bin/env node
// Exports contract ABIs (from Foundry artifacts) and deployed addresses (from broadcast files)
// into packages/shared. Run via `make export-abis` after `forge build` / a deploy.
//
//   node scripts/export-abis.mjs                 export ABIs, refresh addresses for any chain
//                                                that has a broadcast file
//   node scripts/export-abis.mjs --abis-only     only ABIs
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { getAddress } from "viem";

const here = dirname(fileURLToPath(import.meta.url));
const pkg = join(here, "..");
const contracts = join(pkg, "..", "..", "contracts");

const NAMES = ["EnergyToken", "MockUSDC", "WattSwapExchange", "MeterRegistry", "PriceOracle"];
const CHAINS = { anvil: 31337, sepolia: 11155111 };

const abisOnly = process.argv.includes("--abis-only");

mkdirSync(join(pkg, "src", "abis", "json"), { recursive: true });

const lowerFirst = (s) => s[0].toLowerCase() + s.slice(1);

for (const name of NAMES) {
  const artifact = join(contracts, "out", `${name}.sol`, `${name}.json`);
  if (!existsSync(artifact)) {
    console.error(`missing artifact ${artifact}; run \`forge build\` first`);
    process.exit(1);
  }
  const { abi } = JSON.parse(readFileSync(artifact, "utf8"));
  const body =
    `// GENERATED by scripts/export-abis.mjs from contracts/out. Do not edit.\n` +
    `export const ${lowerFirst(name)}Abi = ${JSON.stringify(abi, null, 2)} as const;\n`;
  writeFileSync(join(pkg, "src", "abis", `${name}.ts`), body);
  // Plain JSON copy for non-TypeScript consumers (the Python API and meter simulator).
  writeFileSync(
    join(pkg, "src", "abis", "json", `${name}.json`),
    JSON.stringify(abi, null, 2) + "\n",
  );
}

const barrel =
  `// GENERATED by scripts/export-abis.mjs. Do not edit.\n` +
  NAMES.map((n) => `export { ${lowerFirst(n)}Abi } from "./${n}";`).join("\n") +
  "\n";
writeFileSync(join(pkg, "src", "abis", "index.ts"), barrel);
console.log(`exported ${NAMES.length} ABIs`);

if (!abisOnly) {
  const addrPath = join(pkg, "src", "addresses.json");
  const book = existsSync(addrPath)
    ? JSON.parse(readFileSync(addrPath, "utf8"))
    : { anvil: {}, sepolia: {} };

  for (const [key, chainId] of Object.entries(CHAINS)) {
    const run = join(contracts, "broadcast", "Deploy.s.sol", String(chainId), "run-latest.json");
    if (!existsSync(run)) continue;
    const { transactions } = JSON.parse(readFileSync(run, "utf8"));
    const found = {};
    for (const tx of transactions) {
      if (tx.transactionType === "CREATE" && NAMES.includes(tx.contractName)) {
        found[tx.contractName] = getAddress(tx.contractAddress);
      }
    }
    const missing = NAMES.filter((n) => !(n in found));
    if (missing.length > 0) {
      console.error(`${key}: broadcast is missing ${missing.join(", ")}`);
      process.exit(1);
    }
    book[key] = Object.fromEntries(NAMES.map((n) => [n, found[n]]));
    console.log(`${key} (${chainId}): addresses updated`);
  }
  writeFileSync(addrPath, JSON.stringify(book, null, 2) + "\n");
}
